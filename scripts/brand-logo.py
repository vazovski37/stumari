"""Build every Stumari logo file from the master PNG (docs/product/brand.md).

    pip install pillow numpy potracer
    python scripts/brand-logo.py

Traces the white wordmark in docs/product/brand/logo-master.png to vector paths, then writes
the TS path module, favicon, SVGs and PNG exports. Rerun after replacing the master.
"""

from pathlib import Path

import numpy as np
import potrace
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
MASTER = ROOT / "docs/product/brand/logo-master.png"
WEB = ROOT / "apps/web"
PUBLIC = WEB / "public/brand"

UPSCALE = 8  # trace a smoothed 8x upscale so curves are not pixel stairs
THRESHOLD = 128


def trace_master():
    """Return the wordmark as potrace curves in master pixels, plus the master's size and wordmark box."""
    img = Image.open(MASTER).convert("L")
    ink = np.array(img) > THRESHOLD
    ys, xs = np.where(ink)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max(), ys.max()
    pad = 3
    crop = img.crop((x0 - pad, y0 - pad, x1 + pad + 1, y1 + pad + 1))
    big = crop.resize((crop.width * UPSCALE, crop.height * UPSCALE), Image.LANCZOS)
    big = big.filter(ImageFilter.GaussianBlur(UPSCALE * 0.6))
    # potracer traces the False pixels, so the white letters go in as False.
    paths = potrace.Bitmap(np.array(big) <= THRESHOLD).trace(turdsize=50, alphamax=0.9, opticurve=True, opttolerance=0.4)
    curves = []
    for curve in paths:
        segs = []
        for seg in curve:
            pts = [seg.c, seg.end_point] if seg.is_corner else [seg.c1, seg.c2, seg.end_point]
            segs.append(("L" if seg.is_corner else "C", [(p.x / UPSCALE, p.y / UPSCALE) for p in pts]))
        start = (curve.start_point.x / UPSCALE, curve.start_point.y / UPSCALE)
        curves.append((start, segs))
    return curves, img.size, (x0, y0, x1, y1)


def bbox(curves):
    pts = [p for start, segs in curves for p in [start] + [q for _, qs in segs for q in qs]]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def shift(curves, dx, dy):
    move = lambda p: (p[0] - dx, p[1] - dy)
    return [(move(start), [(kind, [move(q) for q in qs]) for kind, qs in segs]) for start, segs in curves]


def num(v):
    s = f"{v:.1f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def to_d(curves):
    out = []
    for start, segs in curves:
        out.append(f"M{num(start[0])} {num(start[1])}")
        for kind, qs in segs:
            if kind == "L":
                out.append("".join(f"L{num(x)} {num(y)}" for x, y in qs))
            else:
                out.append("C" + " ".join(f"{num(x)} {num(y)}" for x, y in qs))
        out.append("Z")
    return "".join(out)


def polygons(curves, steps=16):
    """Flatten curves to polygons for rasterising."""
    polys = []
    for start, segs in curves:
        pts = [start]
        for kind, qs in segs:
            p0 = pts[-1]
            if kind == "L":
                pts += qs
            else:
                (x1, y1), (x2, y2), (x3, y3) = qs
                for t in np.linspace(0, 1, steps)[1:]:
                    m = 1 - t
                    pts.append((m**3 * p0[0] + 3 * m * m * t * x1 + 3 * m * t * t * x2 + t**3 * x3,
                                m**3 * p0[1] + 3 * m * m * t * y1 + 3 * m * t * t * y2 + t**3 * y3))
        polys.append(pts)
    return polys


def render(size, background, shapes, ss=4):
    """Rasterise (curves, scale, dx, dy, colour) shapes with even-odd fill, 4x supersampled."""
    w, h = size
    out = Image.new("RGB", (w * ss, h * ss), background)
    for curves, scale, dx, dy, colour in shapes:
        mask = np.zeros((h * ss, w * ss), dtype=bool)
        for poly in polygons(curves):
            layer = Image.new("1", (w * ss, h * ss), 0)
            ImageDraw.Draw(layer).polygon([((x * scale + dx) * ss, (y * scale + dy) * ss) for x, y in poly], fill=1)
            mask ^= np.array(layer)
        out.paste(Image.new("RGB", out.size, colour), mask=Image.fromarray(mask.astype(np.uint8) * 255))
    return out.resize(size, Image.LANCZOS)


def svg(view_w, view_h, body):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {num(view_w)} {num(view_h)}">{body}</svg>\n'


def main():
    curves, (mw, mh), (bx0, by0, bx1, by1) = trace_master()
    minx, miny, maxx, maxy = bbox(curves)
    word = shift(curves, minx, miny)
    ww, wh = maxx - minx, maxy - miny

    # The "s" is the first glyph: the only curve that starts in the leftmost 14% of the wordmark.
    s_curves = [c for c in word if c[0][0] < ww * 0.14]
    sx0, sy0, sx1, sy1 = bbox(s_curves)
    s_mark = shift(s_curves, sx0, sy0)
    sw, sh = sx1 - sx0, sy1 - sy0

    word_d, s_d = to_d(word), to_d(s_mark)

    (WEB / "components/brand-paths.ts").write_text(
        "// Generated by scripts/brand-logo.py from docs/product/brand/logo-master.png. Do not edit.\n\n"
        f'export const WORDMARK = {{ width: {num(ww)}, height: {num(wh)}, d: "{word_d}" }} as const;\n\n'
        f'export const S_MARK = {{ width: {num(sw)}, height: {num(sh)}, d: "{s_d}" }} as const;\n',
        encoding="utf-8",
    )

    # Favicon: the s at 60% of the square's height, optically centred.
    k = 32 * 0.6 / sh
    fx, fy = (32 - sw * k) / 2, (32 - sh * k) / 2
    (WEB / "app/icon.svg").write_text(
        svg(32, 32, f'<rect width="32" height="32" fill="#000"/>'
                    f'<path transform="translate({num(fx)} {num(fy)}) scale({k:.4f})" fill="#fff" fill-rule="evenodd" d="{s_d}"/>'),
        encoding="utf-8",
    )

    PUBLIC.mkdir(parents=True, exist_ok=True)
    for name, colour in (("stumari-wordmark.svg", "#000"), ("stumari-wordmark-white.svg", "#fff")):
        (PUBLIC / name).write_text(svg(ww, wh, f'<path fill="{colour}" fill-rule="evenodd" d="{word_d}"/>'), encoding="utf-8")

    # Master composition on a square: keep the master's left margin and wordmark width as fractions of
    # its width, and its bottom margin as a fraction of its height.
    left, width, bottom = bx0 / mw, (bx1 - bx0 + 1) / mw, (mh - by1 - 1) / mh
    S = 1024
    k = S * width / ww
    lx, ly = S * left, S - S * bottom - wh * k
    (PUBLIC / "stumari-logo.svg").write_text(
        svg(S, S, f'<rect width="{S}" height="{S}" fill="#000"/>'
                  f'<path transform="translate({num(lx)} {num(ly)}) scale({k:.4f})" fill="#fff" fill-rule="evenodd" d="{word_d}"/>'),
        encoding="utf-8",
    )
    render((S, S), "#000", [(word, k, lx, ly, "#fff")]).save(PUBLIC / "stumari-logo-1024.png", optimize=True)

    # Avatar: centred at 62% width so a circular crop never touches it.
    k = S * 0.62 / ww
    render((S, S), "#000", [(word, k, (S - ww * k) / 2, (S - wh * k) / 2, "#fff")]).save(
        PUBLIC / "stumari-avatar-1024.png", optimize=True)

    # Icon: the s at 56% height.
    I = 512
    k = I * 0.56 / sh
    render((I, I), "#000", [(s_mark, k, (I - sw * k) / 2, (I - sh * k) / 2, "#fff")]).save(
        PUBLIC / "stumari-icon-512.png", optimize=True)

    print(f"wordmark {num(ww)}x{num(wh)} ({len(word_d)} chars), s {num(sw)}x{num(sh)}; wrote brand-paths.ts, icon.svg, public/brand/*")


if __name__ == "__main__":
    main()
